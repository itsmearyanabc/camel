const DICTIONARIES: Record<BotLanguage, Dict> = { EN, RU, AR, TR, ZH, ES };

/**
 * Look up a translated string, substituting {placeholders}.
 * Falls back to English, then to the key itself, so a missing translation
 * degrades to readable text instead of an empty message.
 */
export function t(
  lang: string | null | undefined,
  key: string,
  params?: Record<string, string | number>
): string {
  const code: BotLanguage = isBotLanguage(lang) ? lang : "EN";
  let text = DICTIONARIES[code][key] ?? EN[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

/** Human-readable label for a language code, e.g. "🇷🇺 Русский". */
export function languageLabel(lang: string | null | undefined): string {
  return BOT_LANGUAGES.find((l) => l.code === lang)?.label ?? "🇬🇧 English";
}

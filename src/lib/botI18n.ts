/**
 * Telegram bot translations.
 *
 * Mirrors the language set the website offers (see components/LanguageContext.tsx).
 * Relative-import safe: this module has no imports, so it works under both the
 * Next bundler and the tsx runtime the bot process uses.
 *
 * Keys missing from a locale fall back to English rather than rendering blank,
 * so adding a new string never breaks the non-English menus.
 */

export type BotLanguage = "EN" | "RU" | "AR" | "TR" | "ZH" | "ES";

export const BOT_LANGUAGES: Array<{ code: BotLanguage; label: string }> = [
  { code: "EN", label: "🇬🇧 English" },
  { code: "RU", label: "🇷🇺 Русский" },
  { code: "AR", label: "🇦🇪 العربية" },
  { code: "TR", label: "🇹🇷 Türkçe" },
  { code: "ZH", label: "🇨🇳 中文" },
  { code: "ES", label: "🇪🇸 Español" },
];

export function isBotLanguage(value: unknown): value is BotLanguage {
  return typeof value === "string" && BOT_LANGUAGES.some((l) => l.code === value);
}

